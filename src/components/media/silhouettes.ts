export interface FabricTone {
  light: string
  base: string
  dark: string
  /** Обводка швов: на тёмной ткани светлее ткани, на светлой — темнее. */
  seam: string
}

/**
 * Тона ткани по коду цвета товара. Фон карточки всегда тёмный — так витрина
 * читается как один разворот каталога, а вещь на нём отделяется цветом.
 */

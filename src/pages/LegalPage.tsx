export default function LegalPage() {
  const { doc } = useParams<{ doc: string }>()
  const legal = doc ? DOCS[doc] : undefined

  useSeo({
    title: legal?.title ?? 'Документы',
    description: legal?.description,
    canonical: `/legal/${doc}`,
  })

  if (!legal) {
    return (
      <div className="container" style={{ paddingTop: 'calc(var(--header-h) + 80px)', paddingBottom: 'var(--section-y)' }}>
        <EmptyState
          title="Документ не найден"
          action={<ButtonLink to="/">На главную</ButtonLink>}
        />
      </div>
    )
  }

  return (
    <>
      <div className="container-narrow page-head">
        <nav className="crumbs" aria-label="Хлебные крошки">
          <Link to="/">Главная</Link>
          <span className="crumbs__sep">/</span>
          <span>{legal.title}</span>
        </nav>
        <Reveal mode="up">
          <h1 className="page-title" style={{ fontSize: 'var(--fs-2xl)' }}>
            {legal.title}
          </h1>
        </Reveal>
        <div style={{ marginTop: 'var(--s-4)' }}>
          <Badge tone="warning">Требует проверки юристом перед запуском</Badge>
        </div>
      </div>

      <div className="container-narrow" style={{ paddingBottom: 'var(--section-y)' }}>
        <div style={{ display: 'grid', gap: 'clamp(24px, 3vw, 40px)' }}>
          {legal.sections.map((section, index) => (
            <Reveal key={section.heading} mode="up" delay={index * 50}>
              <section>
                <h2
                  style={{
                    fontFamily: 'var(--f-mono)',
                    fontSize: 'var(--fs-sm)',
                    letterSpacing: 'var(--ls-wide)',
                    textTransform: 'uppercase',
                    color: 'var(--c-cream-100)',
                    marginBottom: 14,
                  }}
                >
                  {section.heading}
                </h2>
                <div style={{ display: 'grid', gap: 12 }}>
                  {section.paragraphs.map((text, i) => (
                    <p key={i} style={{ color: 'var(--c-text-dim)', lineHeight: 1.8, fontSize: 'var(--fs-sm)' }}>
                      {text}
                    </p>
                  ))}
                </div>
              </section>
            </Reveal>
          ))}
        </div>
      </div>
    </>
  )
}
